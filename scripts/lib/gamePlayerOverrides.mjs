export function getSourcePlayerOverride(answer) {
  return SOURCE_PLAYER_OVERRIDES[normalizeName(answer)] ?? null;
}

export function getRetiredPlayer(answer) {
  const key = normalizeName(answer);
  return RETIRED_PLAYERS.find((player) => normalizeName(player.name) === key) ?? null;
}
