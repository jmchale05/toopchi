function retired(name, nationality, age, firstname, lastname) {
  const parts = name.split(" ").filter(Boolean);
  return {
    name,
    firstname: firstname ?? parts[0] ?? name,
    lastname: lastname ?? (parts.slice(1).join(" ") || parts[0] || name),
    age,
    nationality,
    club: "Retired",
    retired: true,
  };
}

